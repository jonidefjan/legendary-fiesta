// Generates docs/items.md from game/assets/items.json, game/locales/items.en.js
// and ITEM_ELEMENTS in game/src/item-art.js. Run: npm run docs:items
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(root, "docs", "items.md");

const RARITY_ORDER = ["common", "uncommon", "rare", "epic", "legendary", "mythic"];
const TYPES = [
  ["weapon", "Weapons"],
  ["armor", "Armor"],
  ["relic", "Relics"],
  ["mythic", "Mythic items"],
];

const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const cell = (s) => String(s ?? "").replace(/\|/g, "\|").replace(/\s*\n\s*/g, " ").trim() || "-";

function cooldown(ms) {
  if (!ms) return "passive";
  const s = ms / 1000;
  return `${Number.isInteger(s) ? s : s.toFixed(1)}s`;
}

// Builds the markdown in memory (no file writes), so tests can compare it with docs/items.md.
export async function buildItemsDoc() {
  const items = JSON.parse(readFileSync(path.join(root, "game/assets/items.json"), "utf8"));
  const en = (await import(pathToFileURL(path.join(root, "game/locales/items.en.js")).href)).default;
  const { ITEM_ELEMENTS } = await import(pathToFileURL(path.join(root, "game/src/item-art.js")).href);

  const lines = [
    "# Item reference",
    "",
    "<!-- Generated by scripts/items-doc.mjs (npm run docs:items). Do not edit by hand. -->",
    "",
    `${items.length} items. Cooldown is the base value at level 1. Every item declares its own per-level growth, in its effect text (see docs/design/effects-v2.md); nothing scales by default. Items reach level 5. The enchant column shows what each tier unlocks: the first enchant at level 3 and the extra enchant at level 5 (the evolved forms use the levels written in their texts). Common items evolve at level 5 into a form that levels up without limit, by rewards and kills; the form's rarity rises with its level (uncommon, rare at 10, epic at 15, legendary at 20). Element is the badge shown on the item icon. Mythic items have no levels: they are bought once in the title shop (1000 fragments each), only one can be carried per run, and they act on every click or tap on the arena (up to 8 per second) instead of on a cooldown.`,
    "",
  ];

  for (const [type, title] of TYPES) {
    const list = items
      .filter((i) => i.type === type)
      .sort((a, b) => RARITY_ORDER.indexOf(a.rarity) - RARITY_ORDER.indexOf(b.rarity) || (a.evolvedFrom ? 1 : 0) - (b.evolvedFrom ? 1 : 0));
    lines.push(`## ${title} (${list.length})`, "");
    lines.push("| Icon | Name | Rarity | Cooldown | Element | Effect | Enchant |");
    lines.push("| --- | --- | --- | --- | --- | --- | --- |");
    for (const i of list) {
      const k = (part) => en[`items.${i.id}.${part}`];
      const rarityText = i.evolvedFrom ? "Uncommon, rising to Legendary" : cap(i.rarity);
      const evolution = i.evolution
        ? ` Evolves into ${en[`items.${i.evolution.into}.name`]} at level ${i.evolution.level}.`
        : "";
      const tiers = [
        k("enchant") && `${i.enchantLevel ? `[N${i.enchantLevel}] ` : ""}${k("enchant")}`,
        k("enchantExtra") && `[N${i.enchantExtraLevel ?? 5}] ${k("enchantExtra")}`,
      ].filter(Boolean);
      lines.push(
        `| ${i.icon} | ${cell(k("name"))} | ${rarityText} | ${i.type === "mythic" ? "click" : cooldown(i.cooldown)} | ${cell(ITEM_ELEMENTS[i.art || i.id])} | ${cell(k("effect") + evolution)} | ${cell(tiers.join(" "))} |`,
      );
    }
    lines.push("");
  }
  return lines.join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, await buildItemsDoc(), "utf8");
  console.log(`Wrote ${path.relative(root, OUT)}`);
}
